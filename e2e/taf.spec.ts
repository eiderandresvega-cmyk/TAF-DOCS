test('archivos inválidos y texto interpretado como texto bajo CSP', async ({ page }) => {
  const documentResponse = await page.goto(QA_DOCUMENTADOR)
  expect(documentResponse?.headers()['content-security-policy']).toContain("object-src 'none'")
  await page.getByRole('button', { name: 'Con Test Scripts' }).click()
  await page.locator('input[accept=".xlsx"]').setInputFiles({ name: 'archivo.xlsx', mimeType: 'application/octet-stream', buffer: Buffer.from('archivo sin contenedor') })
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Crear proyecto' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Proyectos', exact: true }).click()
  await page.getByRole('button', { name: 'Iniciar de cero' }).click()
  const syntheticText = '<img src="/invalid-injection.png" onerror="window.tafInjection=1">'
  await page.getByLabel('Nombre del proyecto').fill(syntheticText)
  await page.getByLabel('QA responsable').fill('QA Demo')
  await page.getByLabel('Responsable de producto').fill('Producto Demo')
  await page.getByRole('button', { name: 'Crear proyecto' }).click()
  await expect(page.getByRole('heading', { name: syntheticText })).toBeVisible()
  await expect(page.locator('img[src="/invalid-injection.png"]')).toHaveCount(0)
})
