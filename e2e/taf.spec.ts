import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { QA_DOCUMENTADOR } from '../src/site-paths'

const sampleCapture = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAwAAAAICAIAAABChommAAAAMklEQVR4nIXCMREAIAADscpBBCKYOyMCES8CEQhEwueSUXRm0VlFZxedU3QoOrfovKI//vV/gVdu7CQAAAAASUVORK5CYII=', 'base64')

test('Excel por arrastre, captura pegada, autosave, PDF, respaldo y recuperación sin red', async ({ page, context, baseURL }) => {
  const faults: string[] = []
  const uploads: string[] = []
  page.on('pageerror', (error) => faults.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') faults.push(message.text()) })
  context.on('request', (request) => {
    if (!['GET', 'HEAD'].includes(request.method()) || new URL(request.url()).origin !== baseURL || request.postData()) {
      uploads.push(`${request.method()} ${request.url()}`)
    }
  })
  await page.goto(QA_DOCUMENTADOR)
  await expect(page.getByRole('heading', { name: 'Documenta tus pruebas QA.' })).toBeVisible()
  const sheetDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Plantilla Excel' }).click()
  const sheet = await sheetDownload
  const sheetBytes = await readFile(await sheet.path())
  expect(sheetBytes.subarray(0, 2).toString()).toBe('PK')
  await page.getByRole('button', { name: 'Con Test Scripts' }).click()
  const sheetDrop = await page.evaluateHandle(({ name, bytes }) => {
    const data = new DataTransfer()
    data.items.add(new File([new Uint8Array(bytes)], name, { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }))
    return data
  }, { name: sheet.suggestedFilename(), bytes: [...sheetBytes] })
  await page.locator('.file-drop').dispatchEvent('drop', { dataTransfer: sheetDrop })
  await expect(page.getByRole('heading', { name: 'Test Script listo' })).toBeVisible()
  await expect(page.getByText('27 columnas válidas')).toBeVisible()
  await page.getByLabel('Nombre del proyecto').fill('Procesamiento local E2E')
  await page.getByLabel('QA responsable').fill('QA Demo')
  await page.getByLabel('Responsable de producto').fill('Producto Demo')
  await page.getByRole('button', { name: 'Crear proyecto' }).click()
  await expect(page.getByRole('heading', { name: 'Procesamiento local E2E' })).toBeVisible()
  await page.locator('.scenario-card').first().click()
  await page.getByLabel('Estado de ejecución').selectOption('Passed')
  await page.getByLabel('Resultado obtenido').fill('Prueba verificada en el navegador.')
  await page.getByLabel('Comentarios').fill('Persistió tras recarga.')
  await page.evaluate((base64) => {
    const data = new DataTransfer()
    data.items.add(new File([Uint8Array.from(atob(base64), (letter) => letter.charCodeAt(0))], 'captura-demo.png', { type: 'image/png' }))
    document.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }))
  }, sampleCapture.toString('base64'))
  await expect(page.getByRole('button', { name: 'Ampliar captura 1' })).toBeVisible()
  await expect(page.getByRole('status').getByText('Guardado localmente')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Comentarios')).toHaveValue('Persistió tras recarga.')
  await expect(page.getByRole('button', { name: 'Ampliar captura 1' })).toBeVisible()
  await page.getByRole('button', { name: /volver a escenarios|escenarios/i }).first().click()
  await page.getByRole('button', { name: 'Exportar PDF' }).click()
  const pdfDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Descargar PDF' }).click()
  expect((await readFile(await (await pdfDownload).path())).subarray(0, 4).toString()).toBe('%PDF')

  const backupDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Copia de respaldo' }).click()
  const backup = await backupDownload
  expect(backup.suggestedFilename()).toMatch(/\.tafproject$/)
  const backupBytes = await readFile(await backup.path())
  await page.getByRole('button', { name: 'Proyectos', exact: true }).click()
  await page.getByRole('button', { name: 'Importar copia', exact: true }).click()
  await page.locator('input[accept=".tafproject"]').setInputFiles({ name: 'copia-demo.tafproject', mimeType: 'application/octet-stream', buffer: backupBytes })
  await expect(page.getByRole('heading', { name: 'Procesamiento local E2E' })).toBeVisible()
  await expect.poll(() => page.evaluate(async () => (await navigator.serviceWorker.ready).active?.state)).toBe('activated')
  await context.setOffline(true)
  const offlineNavigation = await page.reload()
  expect(offlineNavigation?.fromServiceWorker()).toBe(true)
  await expect(page.getByRole('heading', { name: 'Procesamiento local E2E' })).toBeVisible()
  await page.locator('.scenario-card').first().click()
  await expect(page.getByLabel('Comentarios')).toHaveValue('Persistió tras recarga.')
  await expect(page.getByRole('button', { name: 'Ampliar captura 1' })).toBeVisible()
  expect(uploads).toEqual([])
  expect(faults).toEqual([])
})

